// Scans public/projects/<slug>/ for real project media and writes a typed manifest.
// Runs automatically before `pnpm dev` and `pnpm build` (predev/prebuild).
//
// Why a build-time manifest instead of fs calls in components: the carousel is a client
// component and can't touch the filesystem, and a static manifest keeps every page
// fully prerenderable. Drop files in, rebuild, and they're picked up.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'public', 'projects');
const out = path.join(root, 'src', 'content', 'media.generated.ts');

const POSTER = ['avif', 'webp', 'jpg', 'jpeg', 'png'];
const VIDEO = ['webm', 'mp4'];

const media = {};
if (fs.existsSync(dir)) {
  for (const slug of fs.readdirSync(dir).sort()) {
    const folder = path.join(dir, slug);
    if (!fs.statSync(folder).isDirectory()) continue;
    const files = fs.readdirSync(folder);
    const find = (base, exts) => {
      for (const ext of exts) if (files.includes(`${base}.${ext}`)) return `/projects/${slug}/${base}.${ext}`;
      return undefined;
    };
    const entry = {
      poster: find('poster', POSTER),
      video: VIDEO.map((ext) => files.includes(`loop.${ext}`) && { src: `/projects/${slug}/loop.${ext}`, type: `video/${ext}` }).filter(Boolean),
    };
    if (entry.poster || entry.video.length) media[slug] = entry;
  }
}

const body = `// AUTO-GENERATED by scripts/scan-media.mjs — do not edit. Run \`pnpm media\` to refresh.
import type { MediaManifest } from './types';

export const mediaManifest: MediaManifest = ${JSON.stringify(media, null, 2)};
`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev !== body) fs.writeFileSync(out, body);
console.log(`[media] ${Object.keys(media).length} project folder(s) with media`);
